import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The selected direction is authoritative. Sync explicitly to keep deployment independent.
const root = new URL('../', import.meta.url);
const source = process.argv[2] || fileURLToPath(new URL('../strided-design-system.json', root));
const { schema, brand, selected, tokens } = JSON.parse(readFileSync(source, 'utf8'));
writeFileSync(new URL('src/design-system.json', root), JSON.stringify({ schema, brand, selected, tokens }, null, 2) + '\n');
writeFileSync(new URL('src/styles/brand.css', root), '/* Generated by npm run brand:sync. */\n' + tokens.cssText + '\n');
const logo = selected.logo;
const { x, y, width, height } = logo.viewBox;
const bars = logo.bars.map(bar => `<rect x="${bar.offset}" y="${bar.y}" width="${bar.width}" height="${bar.height}" rx="${logo.radius}" fill="${bar.fill}" opacity="${bar.opacity}" stroke="${bar.outline}" stroke-width="${bar.outlineWidth}"/>`).join('');
writeFileSync(new URL('public/favicon.svg', root), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x} ${y} ${width} ${height}">${bars}</svg>\n`);
console.log('Synced the selected Strided palette, typography, and logo.');
